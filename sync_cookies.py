import json

def convert_to_netscape():
    try:
        with open('headers_auth.json', 'r') as f:
            headers = json.load(f)
    except Exception:
        return
    
    cookie_str = headers.get('cookie') or headers.get('Cookie') or ''
    if not cookie_str:
        return
        
    with open('cookies.txt', 'w') as f:
        f.write("# Netscape HTTP Cookie File\n")
        f.write("# This file is generated by yt-dlp.  Do not edit.\n\n")
        
        for cookie in cookie_str.split(';'):
            cookie = cookie.strip()
            if not cookie: continue
            if '=' not in cookie: continue
            
            key, val = cookie.split('=', 1)
            # Just write them for .youtube.com
            domain = '.youtube.com'
            flag = 'TRUE'
            path = '/'
            secure = 'TRUE' if 'Secure' in key else 'FALSE'
            expiration = '1893456000' # Future timestamp
            
            f.write(f"{domain}\t{flag}\t{path}\t{secure}\t{expiration}\t{key}\t{val}\n")

if __name__ == '__main__':
    convert_to_netscape()
    print("Updated cookies.txt")
